import { Calculator, Check, Copy, Download, Leaf, Sparkles, Sprout, TestTube } from "lucide-react";
import { useState } from "react";
import { Bar, BarChart, CartesianGrid, Cell, ResponsiveContainer, Scatter, ScatterChart, Tooltip, XAxis, YAxis } from "recharts";
import { api } from "../services/api";
import type { Analysis } from "../types";
import { Alert, Badge } from "./ui";

const PALETTE = ["#124d36", "#d97706", "#10b981", "#5b4a3a", "#0284c7", "#ca8a04", "#059669", "#7c3aed"];
const LABEL: Record<string, string> = {
  N: "Available Nitrogen (N)",
  P: "Available Phosphorus (P)",
  K: "Available Potassium (K)",
  ph: "Soil Reaction (pH)"
};

export default function ResultView({ a }: { a: Analysis }) {
  const rec = a.crop_recommendations;
  const shap = rec?.explanations?.[0];
  const c = rec?.cluster;

  // Feature 2: Interactive Fertilizer & Amendment Calculator State
  const [area, setArea] = useState<number>(1);
  const [areaUnit, setAreaUnit] = useState<"acre" | "hectare">("acre");
  const [copied, setCopied] = useState(false);

  // Fertilizer calculation logic based on ICAR guidelines & soil parameter ratings
  const multiplier = areaUnit === "acre" ? area : area * 2.471; // 1 ha = 2.471 acres
  
  const nRating = a.soil_health.parameters.N?.rating;
  const pRating = a.soil_health.parameters.P?.rating;
  const kRating = a.soil_health.parameters.K?.rating;
  const phVal = a.soil_health.parameters.ph?.value;

  // Doses per acre in kg
  const ureaPerAcre = nRating === "low" ? 55 : nRating === "medium" ? 35 : 15;
  const sspPerAcre = pRating === "low" ? 75 : pRating === "medium" ? 45 : 20;
  const mopPerAcre = kRating === "low" ? 30 : kRating === "medium" ? 18 : 8;

  const totalUrea = Math.round(ureaPerAcre * multiplier);
  const totalSsp = Math.round(sspPerAcre * multiplier);
  const totalMop = Math.round(mopPerAcre * multiplier);

  const ureaBags = (totalUrea / 45).toFixed(1); // Standard Indian Urea bag = 45kg
  const sspBags = (totalSsp / 50).toFixed(1);   // Standard SSP bag = 50kg
  const mopBags = (totalMop / 50).toFixed(1);   // Standard MOP bag = 50kg

  // Soil pH Amendment
  let amendment = null;
  if (phVal != null) {
    if (phVal < 6.0) {
      const limeKg = Math.round(250 * multiplier);
      amendment = {
        name: "Agricultural Lime (CaCO₃)",
        amount: `${limeKg} kg (${(limeKg / 50).toFixed(1)} bags)`,
        action: "Neutralize soil acidity and unlock fixed Phosphorus.",
        application: "Broadcast evenly 3-4 weeks before sowing and incorporate thoroughly."
      };
    } else if (phVal > 7.8) {
      const gypsumKg = Math.round(200 * multiplier);
      amendment = {
        name: "Agricultural Gypsum (CaSO₄·2H₂O)",
        amount: `${gypsumKg} kg (${(gypsumKg / 50).toFixed(1)} bags)`,
        action: "Remediate sodicity, lower exchangeable sodium, and enhance soil drainage.",
        application: "Incorporate with pre-sowing deep tillage along with organic farmyard manure."
      };
    }
  }

  const copySummary = () => {
    const topCrop = rec?.top_crops[0]?.crop || "N/A";
    const topProb = rec?.top_crops[0] ? (rec.top_crops[0].probability * 100).toFixed(1) + "%" : "";
    const summary = `🌿 SoilWise Analysis Report
Field: ${a.location || "Plot"}
Top Recommended Crop: ${topCrop.toUpperCase()} (${topProb} confidence)
Secondary Crops: ${rec?.top_crops.slice(1).map(x => `${x.crop} (${(x.probability * 100).toFixed(0)}%)`).join(", ") || "None"}

📊 Soil Health Screening:
- Nitrogen (N): ${a.soil_health.parameters.N?.value ?? "-"} (${nRating || "N/A"})
- Phosphorus (P): ${a.soil_health.parameters.P?.value ?? "-"} (${pRating || "N/A"})
- Potassium (K): ${a.soil_health.parameters.K?.value ?? "-"} (${kRating || "N/A"})
- Soil pH: ${phVal ?? "-"} (${a.soil_health.ph_interpretation?.class || "N/A"})

💡 Dosage Estimate for ${area} ${areaUnit}(s):
- Urea (46% N): ~${totalUrea} kg (${ureaBags} bags)
- SSP (16% P₂O₅): ~${totalSsp} kg (${sspBags} bags)
- MOP (60% K₂O): ~${totalMop} kg (${mopBags} bags)
${amendment ? `- Soil Conditioner: ${amendment.name} ~${amendment.amount}` : ""}

Generated by SoilWise Agritech AI.`;

    navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 3000);
  };

  return (
    <div className="stack">
      {/* Action Bar */}
      <div className="row" style={{ justifyContent: "space-between" }}>
        {a.saved && a.analysis_id ? (
          <Alert kind="info">Analysis successfully recorded in database.</Alert>
        ) : a.save_error ? (
          <Alert kind="warn">Database offline: {a.save_error}</Alert>
        ) : <div />}

        <div className="row">
          <button className="btn ghost" onClick={copySummary} title="Copy summary for WhatsApp or records">
            {copied ? <><Check size={16} color="#10b981" /> Copied!</> : <><Copy size={16} /> Copy Summary</>}
          </button>
          {a.analysis_id && (
            <a className="btn ghost" href={api.reportUrl(a.analysis_id)} target="_blank" rel="noreferrer">
              <Download size={16} /> Download Official PDF Report
            </a>
          )}
        </div>
      </div>

      {/* Recommended Crops Card */}
      <div className="card">
        <div className="row" style={{ gap: 8, marginBottom: 12 }}>
          <Sprout size={22} color="#124d36" />
          <h2>AI Crop Recommendation &amp; Suitability Ranking</h2>
        </div>

        {rec ? (
          <>
            {rec.warnings.map((w) => (
              <div key={w} style={{ marginTop: 8 }}>
                <Alert kind="warn">{w}</Alert>
              </div>
            ))}
            <div style={{ marginTop: 12 }}>
              {rec.top_crops.map((t, i) => (
                <div className="crop" key={t.crop}>
                  <span className="rank">#{i + 1}</span>
                  <span className="name">{t.crop}</span>
                  <div className="bar" aria-hidden>
                    <i style={{ width: `${t.probability * 100}%` }} />
                  </div>
                  <b style={{ minWidth: 60, textAlign: "right" }}>{(t.probability * 100).toFixed(1)}%</b>
                </div>
              ))}
            </div>
            <p className="hint" style={{ marginTop: 14 }}>
              {rec.probability_note} AI Model: <strong>{rec.model}</strong> ({rec.model_version})
              {rec.model_test_accuracy != null && (
                <> with benchmark test accuracy of <strong>{(rec.model_test_accuracy * 100).toFixed(1)}%</strong></>
              )}.
            </p>
          </>
        ) : (
          <Alert kind="info">{a.crop_recommendation_skipped ?? "No crop recommendation available."}</Alert>
        )}
      </div>

      {/* Feature 2: Interactive Fertilizer & Soil Amendment Dosage Planner */}
      <div className="calc-box">
        <div className="calc-header">
          <div>
            <h3 style={{ display: "flex", alignItems: "center", gap: 8 }}>
              <Calculator size={20} color="#124d36" />
              Interactive Fertilizer &amp; Soil Amendment Dosage Calculator
            </h3>
            <p className="hint" style={{ marginTop: 4 }}>
              Tailored replenishment quantities calculated for your soil deficit levels and farm size (based on ICAR guidelines).
            </p>
          </div>

          <div className="row" style={{ background: "#ffffff", padding: "6px 12px", borderRadius: 8, border: "1px solid #d0e4d7" }}>
            <label htmlFor="farm-area" style={{ margin: 0, fontSize: "0.84rem", fontWeight: 700 }}>
              Farm Size:
            </label>
            <input
              id="farm-area"
              type="number"
              min="0.1"
              max="1000"
              step="0.5"
              value={area}
              onChange={(e) => setArea(Math.max(0.1, Number(e.target.value) || 1))}
              style={{ width: 70, padding: "4px 8px" }}
            />
            <select
              value={areaUnit}
              onChange={(e) => setAreaUnit(e.target.value as "acre" | "hectare")}
              style={{ width: 100, padding: "4px 8px" }}
            >
              <option value="acre">Acres</option>
              <option value="hectare">Hectares</option>
            </select>
          </div>
        </div>

        <div className="calc-grid">
          {/* Nitrogen / Urea Card */}
          <div className={`calc-card ${nRating === "low" ? "urgent" : nRating === "medium" ? "normal" : "maintenance"}`}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
              <strong style={{ fontSize: "0.95rem" }}>Urea (46% N)</strong>
              <Badge kind={nRating}>{nRating || "adequate"}</Badge>
            </div>
            <div className="calc-amount">{totalUrea} kg</div>
            <span style={{ fontSize: "0.85rem", color: "#526359", fontWeight: 600 }}>
              Approx. <strong>{ureaBags} bags</strong> (45 kg each)
            </span>
            <p className="hint" style={{ margin: "4px 0 0" }}>
              Split application: 50% basal at sowing, 50% top-dressing after first weeding.
            </p>
          </div>

          {/* Phosphorus / SSP Card */}
          <div className={`calc-card ${pRating === "low" ? "urgent" : pRating === "medium" ? "normal" : "maintenance"}`}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
              <strong style={{ fontSize: "0.95rem" }}>Single Superphosphate (SSP)</strong>
              <Badge kind={pRating}>{pRating || "adequate"}</Badge>
            </div>
            <div className="calc-amount">{totalSsp} kg</div>
            <span style={{ fontSize: "0.85rem", color: "#526359", fontWeight: 600 }}>
              Approx. <strong>{sspBags} bags</strong> (50 kg each)
            </span>
            <p className="hint" style={{ margin: "4px 0 0" }}>
              100% basal dose during soil preparation. Supplies both Phosphorus &amp; Sulfur.
            </p>
          </div>

          {/* Potassium / MOP Card */}
          <div className={`calc-card ${kRating === "low" ? "urgent" : kRating === "medium" ? "normal" : "maintenance"}`}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
              <strong style={{ fontSize: "0.95rem" }}>Muriate of Potash (MOP)</strong>
              <Badge kind={kRating}>{kRating || "adequate"}</Badge>
            </div>
            <div className="calc-amount">{totalMop} kg</div>
            <span style={{ fontSize: "0.85rem", color: "#526359", fontWeight: 600 }}>
              Approx. <strong>{mopBags} bags</strong> (50 kg each)
            </span>
            <p className="hint" style={{ margin: "4px 0 0" }}>
              Apply at basal stage or split in light soils. Increases drought and pest resistance.
            </p>
          </div>

          {/* Amendment Card if applicable */}
          {amendment && (
            <div className="calc-card urgent" style={{ gridColumn: "1 / -1" }}>
              <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
                <strong style={{ color: "#991b1b", fontSize: "0.95rem" }}>
                  ⚠️ Critical Soil Conditioning: {amendment.name}
                </strong>
                <Badge kind="high">pH {phVal}</Badge>
              </div>
              <div className="calc-amount" style={{ color: "#991b1b" }}>{amendment.amount}</div>
              <p style={{ margin: 0, fontSize: "0.88rem", fontWeight: 600 }}>{amendment.action}</p>
              <p className="hint" style={{ margin: 0 }}>{amendment.application}</p>
            </div>
          )}
        </div>
        <p className="hint" style={{ marginTop: 12, fontSize: "0.78rem" }}>
          *Note: Dosages are agronomic estimates for general field crops. For commercial horticulture and cash crops, consult your local Krishi Vigyan Kendra (KVK).
        </p>
      </div>

      {/* SHAP Explainability Card */}
      {shap && rec && (
        <div className="card">
          <div className="row" style={{ gap: 8, marginBottom: 8 }}>
            <Sparkles size={20} color="#d97706" />
            <h2>Feature Contribution &amp; Explainability (SHAP Analysis)</h2>
          </div>
          <p style={{ margin: "6px 0 14px", fontSize: "0.95rem" }}>{rec.explanation_text}</p>
          <div style={{ height: 260 }}>
            <ResponsiveContainer>
              <BarChart data={shap.contributions} layout="vertical" margin={{ left: 20 }}>
                <CartesianGrid horizontal={false} stroke="#e2e8e2" />
                <XAxis type="number" />
                <YAxis type="category" dataKey="feature" width={95} />
                <Tooltip formatter={(v: number) => v.toFixed(4)} labelFormatter={(l) => `Feature: ${l}`} />
                <Bar dataKey="shap" name="SHAP Impact Value">
                  {shap.contributions.map((s) => (
                    <Cell key={s.feature} fill={s.shap >= 0 ? "#124d36" : "#d97706"} />
                  ))}
                </Bar>
              </BarChart>
            </ResponsiveContainer>
          </div>
          <p className="hint" style={{ marginTop: 10 }}>
            <strong style={{ color: "#124d36" }}>Green bars</strong> show parameters pushing the prediction towards {shap.crop}, while <strong style={{ color: "#d97706" }}>amber bars</strong> exerted opposing influence. {shap.note}
          </p>
        </div>
      )}

      {/* Soil Health Screening Table */}
      <div className="card">
        <div className="row" style={{ gap: 8, marginBottom: 12 }}>
          <TestTube size={20} color="#124d36" />
          <h2>Soil Health Screening &amp; Nutrient Deficiencies</h2>
        </div>
        <table>
          <thead>
            <tr>
              <th>Nutrient / Parameter</th>
              <th>Measured Value</th>
              <th>Verification Status</th>
              <th>Screening Classification</th>
            </tr>
          </thead>
          <tbody>
            {Object.entries(a.soil_health.parameters).map(([k, p]) => (
              <tr key={k}>
                <td style={{ fontWeight: 600 }}>{LABEL[k] ?? k}</td>
                <td>{p.value ?? "-"}</td>
                <td><Badge kind={p.status}>{p.status}</Badge></td>
                <td>{p.rating ? <Badge kind={p.rating}>{p.rating}</Badge> : p.class ?? "-"}</td>
              </tr>
            ))}
          </tbody>
        </table>

        {a.soil_health.ph_interpretation && (
          <p style={{ marginTop: 14 }}>
            <strong>Soil Reaction (pH):</strong> {a.soil_health.ph_interpretation.advice}
          </p>
        )}
        {a.soil_health.potential_deficiencies.map((d) => (
          <p key={d.nutrient} style={{ margin: "6px 0" }}>
            <strong style={{ color: "#b91c1c" }}>Potential {d.nutrient} Deficiency:</strong> {d.advice}
          </p>
        ))}
        <p className="hint" style={{ marginTop: 14 }}>
          {a.npk_unit === "dataset_scale"
            ? "N/P/K ratings calibrated relative to the training dataset terciles. "
            : "Screened against ICAR general agronomic rating ranges. "}
          {a.soil_health.disclaimer}
        </p>
      </div>

      {/* General Management Practices */}
      <div className="card">
        <div className="row" style={{ gap: 8, marginBottom: 10 }}>
          <Leaf size={20} color="#10b981" />
          <h2>Recommended Agronomic Best Practices</h2>
        </div>
        <ul style={{ paddingLeft: 20, margin: "6px 0" }}>
          {a.soil_health.general_improvements.map((g) => (
            <li key={g} style={{ marginBottom: 6 }}>{g}</li>
          ))}
        </ul>
      </div>

      {/* Cluster Analysis Card */}
      {c && (
        <div className="card">
          <h2>Similar Soil Profiles (K-Means Cluster #{c.cluster_id})</h2>
          <div style={{ height: 280, marginTop: 12 }}>
            <ResponsiveContainer>
              <ScatterChart margin={{ left: 0, right: 10 }}>
                <CartesianGrid stroke="#e2e8e2" />
                <XAxis type="number" dataKey="x" name="Principal Component 1 (PC1)" />
                <YAxis type="number" dataKey="y" name="Principal Component 2 (PC2)" />
                <Tooltip cursor={{ strokeDasharray: "3 3" }} />
                <Scatter name="Historical Samples" data={c.background} fill="#8fa88f">
                  {c.background.map((p, i) => (
                    <Cell key={i} fill={PALETTE[p.cluster % PALETTE.length]} fillOpacity={0.4} />
                  ))}
                </Scatter>
                <Scatter name="Current Soil Sample" data={[{ x: c.point[0], y: c.point[1] }]} fill="#e11d48" shape="star" />
              </ScatterChart>
            </ResponsiveContainer>
          </div>
          <p className="hint" style={{ marginTop: 10 }}>
            2-D PCA Projection (captures {(c.explained_variance_2d * 100).toFixed(0)}% of dataset variance). The red star represents your submitted soil profile mapped against training clusters.
          </p>
        </div>
      )}
    </div>
  );
}
